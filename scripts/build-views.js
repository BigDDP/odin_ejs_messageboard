// Workers can't compile templates at runtime (no eval / new Function),
// so compile every .ejs view to plain JS functions ahead of time.
const fs = require("node:fs");
const path = require("node:path");
const ejs = require("ejs");

const viewsDir = path.join(__dirname, "../src/views");
const outFile = path.join(__dirname, "../src/views.generated.js");

// Every variable the views use. `with` isn't allowed in bundled (strict) code.
const locals = ["globalMessages", "messages", "message", "dateFormatter"];

const files = fs.readdirSync(viewsDir, { recursive: true }).filter((f) => f.endsWith(".ejs"));

const entries = files.map((file) => {
  const name = file.replace(/\\/g, "/").replace(/\.ejs$/, "");
  const template = new ejs.Template(fs.readFileSync(path.join(viewsDir, file), "utf8"), {
    compileDebug: false,
  });
  template.generateSource();
  return `  ${JSON.stringify(name)}: function (locals, include) {
    const { ${locals.join(", ")} } = locals;
    let __output = "";
    const __append = (s) => { if (s !== undefined && s !== null) __output += s; };
    ${template.source}
    return __output;
  },`;
});

fs.writeFileSync(
  outFile,
  `// Generated by scripts/build-views.js — do not edit\nconst { escapeXML: escapeFn } = require("ejs");\n\nmodule.exports = {\n${entries.join("\n")}\n};\n`
);
console.log(`Compiled ${files.length} views -> src/views.generated.js`);
